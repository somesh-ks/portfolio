// Builds engine/fonts.data.ts for the curated list (engine/fonts.curated.ts):
// metrics from @capsizecss/metrics, facts from Google Fonts metadata, and
// tabular figures and download size from the regular Latin woff2 itself.
// Needs the network; run with `bun run fonts` and commit the output.
import { entireMetricsCollection as all } from "@capsizecss/metrics/entireMetricsCollection";
import * as fontkit from "fontkit";
import { CURATED } from "../src/lib/spring/fonts.curated";

type M = {
  capHeight: number;
  ascent: number;
  descent: number;
  lineGap: number;
  unitsPerEm: number;
  xHeight: number;
  xWidthAvg: number;
};
type GF = {
  family: string;
  subsets: string[];
  fonts: Record<string, unknown>;
  axes: { tag: string; min: number; max: number }[];
  designers: string[];
  popularity: number;
  dateAdded: string;
  isOpenSource: boolean;
};

const metrics = all as unknown as Record<string, M>;
const pick = (m: M) => ({
  ascent: m.ascent,
  descent: m.descent,
  lineGap: m.lineGap,
  unitsPerEm: m.unitsPerEm,
  xHeight: m.xHeight,
  xWidthAvg: m.xWidthAvg,
});

const meta = (await (await fetch("https://fonts.google.com/metadata/fonts")).json()) as {
  familyMetadataList: GF[];
};
const byFamily = new Map(meta.familyMetadataList.map((g) => [g.family, g]));

// A modern UA gets woff2 back; the last @font-face block is the Latin subset.
const UA =
  "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
async function regularLatin(family: string): Promise<{ bytes: number; tnum: boolean }> {
  const css = await (
    await fetch(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, "+")}`, {
      headers: { "User-Agent": UA },
    })
  ).text();
  const urls = [...css.matchAll(/url\((https:[^)]+\.woff2)\)/g)].map((m) => m[1]!);
  const url = urls.at(-1);
  if (!url) throw new Error(`no woff2 for ${family}`);
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  const font = fontkit.create(buf) as fontkit.Font;
  return { bytes: buf.length, tnum: font.availableFeatures.includes("tnum") };
}

const SCRIPT: Record<string, string> = {
  latin: "Latin",
  "latin-ext": "Latin Extended",
  cyrillic: "Cyrillic",
  "cyrillic-ext": "Cyrillic Extended",
  greek: "Greek",
  "greek-ext": "Greek Extended",
  vietnamese: "Vietnamese",
  hebrew: "Hebrew",
  arabic: "Arabic",
  devanagari: "Devanagari",
};

const fonts: Record<string, unknown> = {};
for (const [family, c] of Object.entries(CURATED)) {
  const m = metrics[c.key];
  const g = byFamily.get(family);
  if (!m) throw new Error(`missing metrics: ${family}`);
  if (!g) throw new Error(`missing Google Fonts metadata: ${family}`);
  const weights = [
    ...new Set(
      Object.keys(g.fonts)
        .filter((k) => /^\d+$/.test(k))
        .map(Number),
    ),
  ].sort((a, b) => a - b);
  const wght = g.axes.find((a) => a.tag === "wght");
  const { bytes, tnum } = await regularLatin(family);
  fonts[family] = {
    tag: c.genre,
    jobs: c.jobs,
    feel: c.feel,
    note: c.note,
    weights,
    variable: wght ? [wght.min, wght.max] : null,
    italic: Object.keys(g.fonts).some((k) => k.endsWith("i")),
    scripts: g.subsets.filter((s) => s in SCRIPT).map((s) => SCRIPT[s]),
    tnum,
    kb: Math.round(bytes / 1024),
    popularity: g.popularity,
    license: g.isOpenSource ? "OFL" : "other",
    ...pick(m),
  };
  console.warn(family, weights.join(","), tnum ? "tnum" : "-", `${Math.round(bytes / 1024)}KB`);
}

const fallbacks = {
  Arial: "arial",
  "Times New Roman": "timesNewRoman",
  "Courier New": "courierNew",
};
const fb: Record<string, unknown> = {};
for (const [family, key] of Object.entries(fallbacks)) fb[family] = pick(metrics[key]!);

await Bun.write(
  "src/lib/spring/fonts.data.ts",
  `// Generated by scripts/build-fonts.ts. Do not edit; change src/lib/spring/fonts.curated.ts and run bun scripts/spring-fonts.ts.\n` +
    `export const FONTS = ${JSON.stringify(fonts, null, 2)} as const;\n\n` +
    `export const FALLBACKS = ${JSON.stringify(fb, null, 2)} as const;\n`,
);
console.warn(`wrote ${Object.keys(fonts).length} fonts`);
