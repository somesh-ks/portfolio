/**
 * One-off: turns the claude.dev ride sprites (public/runner/rides.json) into checked-in ASCII for
 * src/lib/stickers/items/ride-data.ts. Nothing is decoded or fetched at runtime.
 * Run: `bun scripts/extract-rides.ts`. The decoder is the one in src/lib/runner/claude-sprites.ts
 * (base string plus per-frame deltas, palette indices, 255 = empty).
 *
 * Only the vehicle's pixels are kept (the sprite's own mascot pixels are dropped, our rig draws the
 * mascot). `origin` is the sprite cell that lines up with the mascot's top-left (0, 0).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

interface Raw {
  w: number;
  h: number;
  palette: string[];
  base: string;
  deltas: string[];
}

function decode(raw: Raw): Uint8Array[] {
  const current = Uint8Array.from(raw.base, (ch) => (ch === "." ? 255 : Number(ch)));
  const frames = [current.slice()];
  for (const delta of raw.deltas) {
    for (const token of delta ? delta.split(",") : []) {
      if (!token) continue;
      const value = token.at(-1);
      current[parseInt(token.slice(0, -1), 36)] = value === "." ? 255 : Number(value);
    }
    frames.push(current.slice());
  }
  return frames;
}

interface Spec {
  loop: readonly [number, number];
  mascot: number[];
  vehicle: number[];
  origin: readonly [number, number];
  /** Drops vehicle pixels this returns true for (the bike's helmet). */
  skip?: (x: number, y: number, v: number) => boolean;
}

const SPECS: Record<string, Spec> = {
  skate: { loop: [31, 33], mascot: [0, 2, 3], vehicle: [1, 4], origin: [0, 7] },
  scooter: { loop: [26, 28], mascot: [0, 1, 2], vehicle: [3, 4, 5, 6, 7, 8], origin: [8, 6] },
  bike: {
    loop: [12, 20],
    mascot: [0, 1, 2],
    vehicle: [3, 4, 5, 6],
    origin: [9, 10],
    skip: (_x, y, v) => y <= 14 && (v === 3 || v === 4),
  },
};

const rides = JSON.parse(
  readFileSync(path.join(import.meta.dir, "../public/runner/rides.json"), "utf8"),
) as Record<string, Raw>;

let out = `// Generated by scripts/extract-rides.ts from public/runner/rides.json. Do not edit by hand.
// Vehicle pixels of the claude.dev rides, 1 sprite pixel = 1 cell. \`at\` is the top-left of the
// rows relative to the mascot's top-left; \`seq\` is the riding loop as indices into \`states\`.
export interface RideSprite {
  at: readonly [number, number];
  palette: Record<string, string>;
  states: string[][];
  seq: number[];
}
export const RIDE_SPRITES: Record<"skate" | "scooter" | "bike", RideSprite> = {\n`;

for (const [id, spec] of Object.entries(SPECS)) {
  const raw = rides[id]!;
  const all = decode(raw);
  const loop = all.slice(spec.loop[0], spec.loop[1]);
  const keep = (x: number, y: number, v: number) =>
    spec.vehicle.includes(v) && !spec.skip?.(x, y, v);
  let x0 = raw.w;
  let y0 = raw.h;
  let x1 = -1;
  let y1 = -1;
  let m: [number, number, number, number] = [raw.w, raw.h, -1, -1];
  for (const px of loop)
    px.forEach((v, i) => {
      const x = i % raw.w;
      const y = Math.floor(i / raw.w);
      if (spec.mascot.includes(v))
        m = [Math.min(m[0], x), Math.min(m[1], y), Math.max(m[2], x), Math.max(m[3], y)];
      if (!keep(x, y, v)) return;
      x0 = Math.min(x0, x);
      y0 = Math.min(y0, y);
      x1 = Math.max(x1, x);
      y1 = Math.max(y1, y);
    });
  console.warn(
    `${id}: mascot box x${m[0]}-${m[2]} y${m[1]}-${m[3]}, vehicle x${x0}-${x1} y${y0}-${y1}`,
  );
  const states: string[][] = [];
  const seq: number[] = [];
  for (const px of loop) {
    const rows: string[] = [];
    for (let y = y0; y <= y1; y++) {
      let row = "";
      for (let x = x0; x <= x1; x++) {
        const v = px[y * raw.w + x]!;
        row += keep(x, y, v) ? String(v) : ".";
      }
      rows.push(row);
    }
    const key = rows.join("\n");
    let k = states.findIndex((s) => s.join("\n") === key);
    if (k < 0) k = states.push(rows) - 1;
    seq.push(k);
  }
  const palette: Record<string, string> = {};
  for (const v of spec.vehicle) palette[String(v)] = raw.palette[v]!.toUpperCase();
  out += `  ${id}: {
    at: [${x0 - spec.origin[0]}, ${y0 - spec.origin[1]}],
    palette: ${JSON.stringify(palette)},
    seq: ${JSON.stringify(seq)},
    states: ${JSON.stringify(states)},
  },\n`;
}
out += "};\n";
writeFileSync(path.join(import.meta.dir, "../src/lib/stickers/items/ride-data.ts"), out);
