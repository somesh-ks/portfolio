/**
 * One-off: turns the claude.dev ride sprites (public/runner/rides.json) into checked-in ASCII and
 * a fitted rider pose for src/lib/stickers/items/ride-data.ts. Nothing is decoded or fetched at
 * runtime. Run: `bun scripts/extract-rides.ts`. The decoder and the fit live in ride-fit.ts.
 *
 * The sprite is cut into the mascot (our rig draws that, posed by the fit) and the vehicle. Each
 * loop frame's vehicle pixels, plus a few body-coloured fill cells where the rig can't reach the
 * original's pixels, are the ride's art, in front of the body; the fitted pose says where the
 * torso, arms and legs go. `at` is the art's top-left in mascot cells.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fitRide, loadRides, RIDE_SPECS, type RidePose } from "./ride-fit";

const rides = loadRides();
let out = `// Generated by scripts/extract-rides.ts from public/runner/rides.json. Do not edit by hand.
// Vehicle pixels of the claude.dev rides, 1 sprite pixel = 1 cell, drawn in front of the rig's
// body. \`at\` is the top-left of the rows in mascot cells; \`seq\` is the riding loop as indices into
// \`states\`; \`pose\` is the fitted rider per loop frame (B and S in the rows are body-coloured fill
// for cells the rig can't reach).
import type { RidePose } from "./types";

export interface RideSprite {
  /** The sprite cell that is the mascot's (0, 0). */
  origin: readonly [number, number];
  at: readonly [number, number];
  palette: Record<string, string>;
  states: string[][];
  seq: number[];
  pose: RidePose[];
  /** Where the eyes look, so they land on the original's. */
  eye: readonly [number, number];
  ground: number;
}
export const RIDE_SPRITES: Record<"skate" | "scooter" | "bike", RideSprite> = {\n`;

// The skateboard rider's arms follow the action, so the fitted arms are not kept.
const skateless = ({ body, legs }: RidePose) => ({ body, legs });

for (const [id, spec] of Object.entries(RIDE_SPECS)) {
  const fit = fitRide(rides[id]!, spec);
  const states: string[][] = [];
  const seq: number[] = [];
  for (const rows of fit.rows) {
    let k = states.findIndex((s) => s.join("\n") === rows.join("\n"));
    if (k < 0) k = states.push(rows) - 1;
    seq.push(k);
  }
  const fill = fit.rows.map((r) => r.join("").replace(/[^BS]/g, "").length);
  console.warn(
    `${id}: origin ${fit.origin}, eye ${fit.eye}, ground ${fit.ground}; per frame bare ${fit.frames.map((f) => f.miss)} (filled), painted-on-empty ${fit.frames.map((f) => f.extra)}, fill cells ${fill}`,
  );
  out += `  ${id}: {
    origin: ${JSON.stringify(fit.origin)},
    at: ${JSON.stringify(fit.at)},
    palette: ${JSON.stringify({ ...fit.palette, B: "#D97757", S: "#BF6747" })},
    seq: ${JSON.stringify(seq)},
    eye: ${JSON.stringify(fit.eye)},
    ground: ${fit.ground},
    pose: ${JSON.stringify(fit.frames.map((f) => (id === "skate" ? skateless(f.pose) : f.pose)))},
    states: ${JSON.stringify(states)},
  },\n`;
}
out += "};\n";
writeFileSync(path.join(import.meta.dir, "../src/lib/stickers/items/ride-data.ts"), out);
