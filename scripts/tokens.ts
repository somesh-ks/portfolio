/**
 * Builds the token layer: Terrazzo emits src/styles/tokens.css from the DTCG
 * files, then this script derives fluid type steps (clamp) from the
 * font.size.*-min / *-max primitives into src/styles/fluid.css.
 * DTCG has no clamp() type, so the interpolation lives here, not in JSON.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

const VIEWPORT_MIN_REM = 22.5; // 360px
const VIEWPORT_MAX_REM = 80; // 1280px

interface DimensionToken {
  $value: { value: number; unit: string };
}

export function fluidCss(primitives: { font: { size: Record<string, unknown> } }): string {
  const sizes = primitives.font.size as Record<string, DimensionToken | string>;
  const steps = Object.keys(sizes)
    .filter((key) => key.endsWith("-min"))
    .map((key) => key.slice(0, -4));
  const lines = steps.map((step) => {
    const min = (sizes[`${step}-min`] as DimensionToken).$value.value;
    const max = (sizes[`${step}-max`] as DimensionToken).$value.value;
    if (max > min * 2.5) throw new Error(`font.size.${step}: max exceeds 2.5x min (WCAG 1.4.4)`);
    const slope = (max - min) / (VIEWPORT_MAX_REM - VIEWPORT_MIN_REM);
    const intercept = min - slope * VIEWPORT_MIN_REM;
    const preferred = `${round(intercept)}rem + ${round(slope * 100)}vw`;
    return `  --step-${step}: clamp(${min}rem, ${preferred}, ${max}rem);`;
  });
  return [
    "/* Generated by scripts/tokens.ts from tokens/primitives.json. Do not edit. */",
    ":root {",
    ...lines,
    "}",
    "",
  ].join("\n");
}

function round(value: number): number {
  return Math.round(value * 10000) / 10000;
}

export function buildTokens(): void {
  const result = spawnSync("bunx", ["tz", "build", "--quiet"], { stdio: "inherit" });
  if (result.status !== 0) throw new Error("tz build failed");
  const primitives = JSON.parse(readFileSync("tokens/primitives.json", "utf8"));
  writeFileSync("src/styles/fluid.css", fluidCss(primitives));
}

if (import.meta.main) buildTokens();
